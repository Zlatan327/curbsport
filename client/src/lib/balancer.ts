export interface BalancedTeam {
  name: string;
  badge: string;
  color: string;
  players: any[];
  avgRep: number;
}

export interface BalancedMatch {
  teamA: BalancedTeam;
  teamB: BalancedTeam;
}

export function balanceSquad(
  players: any[],
  sportType: 'FOOTBALL' | 'BASKETBALL' = 'FOOTBALL'
): BalancedMatch {
  const isBball = sportType === 'BASKETBALL';
  const teamAName = isBball ? 'Team White (Light)' : 'Team Shirts (Bibs)';
  const teamBName = isBball ? 'Team Dark (Colors)' : 'Team Up-Body (No Bibs)';

  // Sort players by reputation score descending
  const sorted = [...players].sort((a, b) => {
    const repA = typeof a === 'object' ? (a.reputationScore ?? 10) : 10;
    const repB = typeof b === 'object' ? (b.reputationScore ?? 10) : 10;
    return repB - repA;
  });

  // Separate Goalkeepers for Football to ensure fair distribution
  let gks: any[] = [];
  let outfield: any[] = [];

  if (!isBball) {
    gks = sorted.filter((p) => {
      const pos = (typeof p === 'object' ? p.footballPosition || p.favoritePosition : '')?.toUpperCase();
      return pos === 'GOALKEEPER' || pos === 'GK' || pos === 'KEEPER';
    });
    outfield = sorted.filter((p) => !gks.includes(p));
  } else {
    outfield = sorted;
  }

  const teamAPlayers: any[] = [];
  const teamBPlayers: any[] = [];

  // Distribute GKs alternately
  gks.forEach((gk, idx) => {
    if (idx % 2 === 0) teamAPlayers.push(gk);
    else teamBPlayers.push(gk);
  });

  // Snake draft distribution for outfield players (1->A, 2->B, 3->B, 4->A...)
  let toggle = true;
  for (let i = 0; i < outfield.length; i += 2) {
    const p1 = outfield[i];
    const p2 = outfield[i + 1];

    if (toggle) {
      if (p1) teamAPlayers.push(p1);
      if (p2) teamBPlayers.push(p2);
    } else {
      if (p1) teamBPlayers.push(p1);
      if (p2) teamAPlayers.push(p2);
    }
    toggle = !toggle;
  }

  const calculateAvg = (list: any[]) => {
    if (!list.length) return 0;
    const total = list.reduce(
      (acc, p) => acc + (typeof p === 'object' ? (p.reputationScore ?? 10) : 10),
      0
    );
    return Math.round(total / list.length);
  };

  return {
    teamA: {
      name: teamAName,
      badge: isBball ? '⚪' : '🟢',
      color: '#00ff66',
      players: teamAPlayers,
      avgRep: calculateAvg(teamAPlayers),
    },
    teamB: {
      name: teamBName,
      badge: isBball ? '⚫' : '🟡',
      color: '#ffd700',
      players: teamBPlayers,
      avgRep: calculateAvg(teamBPlayers),
    },
  };
}

export function formatBalancedSquadWhatsAppMessage(params: {
  pitchName: string;
  sportType: 'FOOTBALL' | 'BASKETBALL';
  teamA: BalancedTeam;
  teamB: BalancedTeam;
  pitchUrl: string;
}): string {
  const isBball = params.sportType === 'BASKETBALL';
  const icon = isBball ? '🏀' : '⚽';

  const formatPlayerList = (list: any[]) => {
    return list
      .map((p) => {
        const name = typeof p === 'string' ? p : p.alias || 'Player';
        const rep = typeof p === 'object' ? (p.reputationScore ?? 10) : 10;
        const pos =
          typeof p === 'object'
            ? (isBball ? p.basketballPosition : p.footballPosition) || p.favoritePosition
            : null;
        const posStr = pos ? ` (${pos})` : '';
        const ballIcon = typeof p === 'object' && p.hasBall ? (isBball ? ' 🏀' : ' ⚽') : '';
        return `• ${name}${posStr} - ⭐${rep} REP${ballIcon}`;
      })
      .join('\n');
  };

  return [
    `${icon} *BALANCED SQUADS FOR ${params.pitchName.toUpperCase()}!*`,
    `⚖️ Generated by Curbsport Squad Balancer`,
    ``,
    `${params.teamA.badge} *${params.teamA.name.toUpperCase()}* (Avg ⭐${params.teamA.avgRep} REP):`,
    formatPlayerList(params.teamA.players),
    ``,
    `${params.teamB.badge} *${params.teamB.name.toUpperCase()}* (Avg ⭐${params.teamB.avgRep} REP):`,
    formatPlayerList(params.teamB.players),
    ``,
    `🔥 *Squads balanced & locked in for kick-off!*`,
    `👉 View live ground radar:`,
    params.pitchUrl,
  ].join('\n');
}
